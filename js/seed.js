// 从课程名反查预置别名
export function suggestAliases(courseName) {
  const name = String(courseName || '').trim();
  if (!name) return [];
  if (COURSE_ALIASES[name]) return [...COURSE_ALIASES[name]];
  // 用户写的可能是别名本身，反查回全称的别名表
  for (const [full, aliases] of Object.entries(COURSE_ALIASES)) {
    if (aliases.includes(name)) return [full, ...aliases.filter((a) => a !== name)];
  }
  return [];
}
